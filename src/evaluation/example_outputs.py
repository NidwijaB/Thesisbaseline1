"""
src/evaluation/example_outputs.py
----------------------------------
Picks a few cut lines from the Part 1 pilot and writes the four systems' answers side by side to
docs/example_outputs.md, for the presentation and the report. The choice follows fixed rules (below), not by
hand, so the examples are not cherry-picked after the fact; each one says which rule picked it. The code shown
is the last lines before the cut (the benchmark text, public data). Pilot, n=50 (n=68 for the staleness case).

    python -m src.evaluation.example_outputs

Rules (ties broken by task id):
  1  both adapter systems exact, base and RAG not          -> "fine-tuning learned the repository's calls"
  2  largest hybrid gain from the staleness view (68 set)  -> "retrieval reaches a file the adapter never saw"
  3  RAG empty or under 5 characters, base fine            -> "RAG failure"
  4  largest RAG gain over base                            -> "retrieval helped the frozen model"
  5  longest hybrid answer                                 -> "hybrid failure"
  6  lowest mean edit similarity over the four systems     -> "hard for everyone"
"""

from __future__ import annotations
import json
from pathlib import Path

from datasets import load_from_disk

R = Path("results")
SYSTEMS = ["base", "rag_only", "finetuning_only", "hybrid"]
LABEL = {"base": "base (plain prompt)", "rag_only": "RAG (plain prompt + 5 chunks)", "finetuning_only": "fine-tuned",
         "hybrid": "hybrid (fine-tuned + 5 chunks)"}


def load(run: str) -> dict:
    return {r["task_id"]: r for r in map(json.loads, open(R / run / "predictions.jsonl", encoding="utf-8"))}


def code_tail(ex: dict, lines: int = 4) -> str:
    return "\n".join(ex["prompt"].split("\n")[-lines:])


def pick(pilot: dict, new_main: dict, new_stale: dict) -> list[tuple[str, str, dict, str]]:
    """[(rule title, task id, runs {label: predictions-row}, note)]"""
    ids = sorted(pilot)
    picks = []
    both = [t for t in ids if pilot[t]["finetuning_only"]["exact_match"] and pilot[t]["hybrid"]["exact_match"]
            and not pilot[t]["base"]["exact_match"] and not pilot[t]["rag_only"]["exact_match"]]
    if both:
        picks.append(("Fine-tuning learned the repository's calls", both[0], {"main view": pilot}, "rule 1"))
    gain = sorted(sorted(new_main), key=lambda t: -(new_stale[t]["hybrid"]["edit_similarity"] - new_main[t]["hybrid"]["edit_similarity"]))
    if gain:
        picks.append(("Retrieval reaches a file the adapter never saw (staleness test, 68 set)", gain[0],
                      {"main view (new file not in index)": new_main, "staleness view (new file in index)": new_stale}, "rule 2"))
    rag_fail = [t for t in ids if len(pilot[t]["rag_only"]["prediction"].strip()) < 5 and pilot[t]["base"]["edit_similarity"] >= 0.4]
    if rag_fail:
        picks.append(("RAG failure: empty or cut-off answer", rag_fail[0], {"main view": pilot}, "rule 3"))
    rag_gain = sorted(ids, key=lambda t: -(pilot[t]["rag_only"]["edit_similarity"] - pilot[t]["base"]["edit_similarity"]))
    picks.append(("Retrieval helped the frozen model", rag_gain[0], {"main view": pilot}, "rule 4"))
    longest = sorted(ids, key=lambda t: -len(pilot[t]["hybrid"]["prediction"]))
    picks.append(("Hybrid failure: runaway answer", longest[0], {"main view": pilot}, "rule 5"))
    hard = sorted(ids, key=lambda t: sum(pilot[t][s]["edit_similarity"] for s in SYSTEMS))
    picks.append(("Hard for every system", hard[0], {"main view": pilot}, "rule 6"))
    return picks


def clip(text: str, n: int = 110) -> str:
    text = text.replace("\n", "\\n")
    return text if len(text) <= n else text[:n] + " ... (cut)"


def main():
    pilot, new_main, new_stale = load("pilot_main_plainbase"), load("new_relevant_main_plainbase"), load("new_relevant_staleness_plainbase")
    ids = set(pilot) | set(new_main)
    data = {ex["metadata"]["task_id"]: ex for ex in load_from_disk("data/crosscodeeval/python")["train"]
            if ex["metadata"]["task_id"] in ids}
    out = ["# Example outputs for the presentation (Part 1 pilot)", "",
           "Generated by `python -m src.evaluation.example_outputs` from `results/pilot_main_plainbase`, "
           "`results/new_relevant_main_plainbase` and `results/new_relevant_staleness_plainbase`. Pilot, n=50 (n=68 for the "
           "staleness case): examples, not evidence. Each example was chosen by a fixed rule (named under its title), not by hand. "
           "Base and RAG use the plain prompt; fine-tuned and hybrid use the training format. Answers are the first line only.", ""]
    for n, (title, tid, runs, rule) in enumerate(pick(pilot, new_main, new_stale), 1):
        ex = data[tid]
        out += [f"## {n}. {title}", "", f"Selected by {rule}. Task `{tid}`, repository `{ex['metadata']['repository']}`.", "",
                "Code before the cut (last lines):", "", "```python", code_tail(ex), "```", "",
                f"Reference (what the file really contains): `{clip(next(iter(runs.values()))[tid]['reference'])}`", "",
                "| System | " + " | ".join(f"Answer, {name}" for name in runs) + " |",
                "|---|" + "---|" * len(runs)]
        for s in SYSTEMS:
            cells = []
            for rows in runs.values():
                r = rows[tid][s]
                shown = clip(r["prediction"]) if r["prediction"].strip() else "(empty)"
                cells.append(f"`{shown}` (edit sim. {r['edit_similarity']:.2f}{', exact' if r['exact_match'] else ''})")
            out.append(f"| {LABEL[s]} | " + " | ".join(cells) + " |")
        out.append("")
    path = Path("docs/example_outputs.md")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(out)} lines)")


if __name__ == "__main__":
    main()
